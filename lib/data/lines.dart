/// 가상 부모가 하는 말 30개.
///
/// 설정할 때 부모의 복제 목소리로 한 번에 미리 만들어 기기에 저장한다.
/// 그래서 공부 중에는 인터넷이 없어도 되고, 추가 요금도 들지 않는다.
///
/// 치환 규칙
///   {c}  → 아이를 부르는 말 (예: '민준아')
///   {me} → '엄마' / '아빠'
enum LineKind { start, drowsy, away, distracted, returned, praise, finish }

const Map<LineKind, List<String>> lineTemplates = {
  LineKind.start: [
    '{c}, 이제 공부 시작하자. {me}가 옆에서 보고 있을게.',
    '자, 집중해서 해보자. 끝나면 칭찬해 줄게.',
    '{c}, 핸드폰 내려놓고 시작! {me}가 지켜본다.',
  ],
  LineKind.drowsy: [
    '{c}, 졸고 있니? 정신 차리자!',
    '어허, 눈 감았다! {c}, 일어나 봐.',
    '{c}, 졸리면 일어나서 기지개 한 번 켜고 와.',
    '벌써 졸면 어떡해. 찬물로 세수하고 오자.',
    '{c}! 자는 거 아니지? 눈 크게 뜨자.',
  ],
  LineKind.away: [
    '{c}, 어디 갔어? 아직 공부 시간이야.',
    '자리 비우면 안 되지. 빨리 돌아와.',
    '{c}, 화장실이야? 얼른 다녀와서 앉자.',
    '{me}가 기다리고 있어. 다시 자리에 앉자.',
    '{c}! 시간 멈췄어. 돌아와야 다시 흘러간다.',
  ],
  LineKind.distracted: [
    '{c}, 어디 보는 거야? 책 보자.',
    '딴짓하지 말고 집중!',
    '{c}, 핸드폰 보는 거 아니지?',
    '눈은 책에! {me}가 다 보고 있어.',
    '{c}, 한눈팔지 말고 조금만 더 힘내자.',
  ],
  LineKind.returned: [
    '왔구나. 다시 시작하자.',
    '좋아, {c}. 이어서 하자.',
    '돌아왔네. 이제 집중!',
    '그래, 앉았으면 다시 힘내 보자.',
  ],
  LineKind.praise: [
    '{c}, 잘하고 있어! {me}가 자랑스럽다.',
    '오, 집중 잘하네. 이대로만 하자.',
    '{c}, 멋지다. 조금만 더 힘내!',
    '이렇게 꾸준히 하는 게 제일 중요해. 잘하고 있어.',
    '{c}, 최고야! 계속 이렇게 하자.',
  ],
  LineKind.finish: [
    '{c}, 수고했어! 오늘 정말 잘했다.',
    '끝! {c}, 끝까지 해내서 {me}가 너무 기쁘다.',
    '고생 많았어. 이제 좀 쉬어도 돼.',
  ],
};

String fillLine(String template, {required String childCall, required String role}) =>
    template.replaceAll('{c}', childCall).replaceAll('{me}', role);

int get totalLineCount =>
    lineTemplates.values.fold(0, (sum, list) => sum + list.length);

